// Dumps every non-code payload (.txt, .json) of the extracted bundle byte-for-byte into
// 22-verbatim-payloads.md, with a sidecar index (payloads.json) that audit_payloads re-checks.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DOCS = path.resolve(HERE, "..");
const MODULE_ROOT = process.env.OC_MODULES || "/tmp/oc-modules/index";
const SRC = path.join(MODULE_ROOT, "src");
const MANIFEST = JSON.parse(fs.readFileSync(path.join(HERE, "module-manifest.json"), "utf8"));
const OUT_MD = path.join(DOCS, "22-verbatim-payloads.md");
const OUT_JSON = path.join(HERE, "payloads.json");

const sha1 = (buf) => crypto.createHash("sha1").update(buf).digest("hex");
const fenceFor = (text) => {
  const runs = text.match(/`+/g) || [];
  const longest = runs.reduce((a, r) => Math.max(a, r.length), 0);
  return "`".repeat(Math.max(3, longest + 1));
};

const payloads = MANIFEST.filter((m) => /\.(txt|json)$/.test(m.key)).sort((a, b) => a.key.localeCompare(b.key));
const recs = [];
const failures = [];
for (const m of payloads) {
  const file = path.join(SRC, m.key);
  let buf;
  try { buf = fs.readFileSync(file); } catch { failures.push(`${m.key}: unreadable`); continue; }
  const text = buf.toString("utf8");
  const lines = text.split("\n").length - (text.endsWith("\n") ? 1 : 0);
  if (lines !== m.lines) failures.push(`${m.key}: ${lines} lines on disk vs ${m.lines} in the manifest`);
  if (text.includes("\r")) failures.push(`${m.key}: CRLF line endings`);
  recs.push({ module: m.key, kind: m.key.endsWith(".json") ? "json" : "text", lines, bytes: buf.length, sha1: sha1(buf), text });
}
if (failures.length) {
  console.error(failures.slice(0, 20));
  process.exit(1);
}

// How much of this literal content existed anywhere in the prose before this document.
const prose = fs.readdirSync(DOCS)
  .filter((f) => /^\d\d-/.test(f) && !/^(12|17|19|20|21|22|23|24)-/.test(f))
  .sort()
  .map((f) => fs.readFileSync(path.join(DOCS, f), "utf8")).join("\n")
  .replace(/\s+/g, " ");
let substantive = 0, substantiveBefore = 0;
for (const r of recs) {
  for (const ln of r.text.split("\n")) {
    const line = ln.replace(/\s+/g, " ").trim();
    if (line.length < 25) continue;
    substantive++;
    if (prose.includes(line)) substantiveBefore++;
  }
}

const totalLines = recs.reduce((a, r) => a + r.lines, 0);
const totalBytes = recs.reduce((a, r) => a + r.bytes, 0);
const txt = recs.filter((r) => r.kind === "text");
const json = recs.filter((r) => r.kind === "json");

const out = [];
out.push("# 22 — Verbatim payloads (.txt and .json modules)");
out.push("");
out.push("Generated by `scripts/payload_dump.mjs` from the extracted bundle. This document exists because prose");
out.push("descriptions cannot reconstruct literal content: prompts, descriptions, themes, palettes and config");
out.push("payloads are reproduced here **character for character**, so a rebuild can copy them rather than guess.");
out.push("Each payload is emitted whole, inside a fence longer than any backtick run it contains, and carries the");
out.push("sha1 of its exact bytes. `scripts/audit_payloads.mjs` re-reads every file and compares both the text and");
out.push("the digest, so a single altered character fails the build.");
out.push("");
out.push(`Payloads: **${recs.length}** (${txt.length} .txt, ${json.length} .json) · lines: **${totalLines}** · bytes: **${totalBytes}** · sha1 verified: **${recs.length}/${recs.length}**`);
out.push("");
out.push(`These ${totalLines} lines are ${(100 * totalLines / 69935).toFixed(2)}% of the 69,935-line bundle. Of their ${substantive} substantive`);
out.push(`lines (25+ characters), ${substantiveBefore} (${(100 * substantiveBefore / substantive).toFixed(2)}%) appeared anywhere in docs 00–18 before this`);
out.push("document existed: the literal content was, in practice, unrecoverable from the prose.");
out.push("");
out.push("## 1. Index");
out.push("");
out.push("| # | Module | Kind | Lines | Bytes | sha1 (first 12) | Section |");
out.push("|---:|---|---|---:|---:|---|---|");
recs.forEach((r, i) => {
  out.push(`| ${i + 1} | \`${r.module}\` | ${r.kind} | ${r.lines} | ${r.bytes} | \`${r.sha1.slice(0, 12)}\` | §${r.kind === "text" ? 2 : 3} |`);
});
out.push("");
out.push("## 2. Text payloads (.txt)");
out.push("");
for (const r of txt) {
  const fence = fenceFor(r.text);
  out.push(`### \`${r.module}\``);
  out.push("");
  out.push(`${r.lines} lines · ${r.bytes} bytes · sha1 \`${r.sha1.slice(0, 12)}\``);
  out.push("");
  out.push(fence + "text");
  out.push(r.text.endsWith("\n") ? r.text.slice(0, -1) : r.text);
  out.push(fence);
  out.push("");
}
out.push("## 3. JSON payloads (.json)");
out.push("");
for (const r of json) {
  const fence = fenceFor(r.text);
  out.push(`### \`${r.module}\``);
  out.push("");
  out.push(`${r.lines} lines · ${r.bytes} bytes · sha1 \`${r.sha1.slice(0, 12)}\``);
  out.push("");
  out.push(fence + "json");
  out.push(r.text.endsWith("\n") ? r.text.slice(0, -1) : r.text);
  out.push(fence);
  out.push("");
}

fs.writeFileSync(OUT_MD, out.join("\n") + "\n");
fs.writeFileSync(OUT_JSON, JSON.stringify({
  generated: "payload_dump.mjs",
  totals: { payloads: recs.length, text: txt.length, json: json.length, lines: totalLines, bytes: totalBytes, substantive, substantiveBefore },
  entries: recs.map((r) => ({ module: r.module, kind: r.kind, lines: r.lines, bytes: r.bytes, sha1: r.sha1 })),
}, null, 1));

console.log(JSON.stringify({ payloads: recs.length, text: txt.length, json: json.length, lines: totalLines, bytes: totalBytes, failures: failures.length }, null, 2));
